'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname,'..');
const context = {window:{}};
vm.createContext(context);
for (const file of ['videos.js','video-gallery.js']) vm.runInContext(fs.readFileSync(path.join(root,'dist/assets',file),'utf8'),context);
const catalog = context.window.youtubeCatalog;
const build = context.window.buildVideoGallery;
const expectedChannels = ['UC6WvDFTjgFk3Q35q4mpaL0g','UCfiQBBY25mMqY4seHB_fCmg'];
assert.deepEqual(Array.from(catalog.channels,channel=>channel.id),expectedChannels);
const ids = new Set();
for (const video of catalog.videos) {
  assert.match(video.id,/^[A-Za-z0-9_-]{11}$/);
  assert(!ids.has(video.id),'Repeated video ID: '+video.id);
  ids.add(video.id);
  assert(expectedChannels.includes(video.channelId));
  assert.equal(video.url,'https://www.youtube.com/watch?v='+video.id);
  assert.match(video.publishedDate,/^20\d\d-\d\d-\d\d$/);
  assert(Number.isFinite(Date.parse(video.publishedAt)));
  assert(Date.parse(video.publishedAt) <= Date.now(),'Upcoming video must not be published as a recording');
  assert.equal(video.image,'assets/video-thumbnails/'+video.id+'.jpg');
  const image = fs.readFileSync(path.join(root,'dist',video.image));
  assert(image.length > 500 && image[0] === 255 && image[1] === 216,'Invalid local thumbnail');
}
const gallery = build(catalog);
const displayed = gallery.groups.flatMap(group=>Array.from(group.sources,source=>source.id));
assert.equal(displayed.length,ids.size,'A recording was dropped while grouping');
assert.equal(new Set(displayed).size,ids.size,'A recording appears in more than one result');
assert(gallery.years.includes('2020') && gallery.years.includes('2026'));
assert(gallery.groups.every((group,index,all)=>!index || group.publishedAt <= all[index-1].publishedAt));
const sample = {...catalog.videos[0],title:'A distinctive scientific lecture about superconductivity | Researcher',publishedDate:'2027-01-09',publishedAt:'2027-01-09T16:00:00Z',duration:3600};
const first = {...sample,id:'AAAAAAAAAAA',channelId:expectedChannels[0]};
const second = {...sample,id:'BBBBBBBBBBB',channelId:expectedChannels[1]};
const fixture = videos=>({channels:catalog.channels,videos});
assert.equal(build(fixture([first,second])).groups.length,1,'Cross-channel copy should be grouped');
assert.equal(build(fixture([first,{...second,channelId:first.channelId}])).groups.length,2,'Distinct uploads from one channel must remain visible');
assert.equal(build(fixture([first,{...second,publishedDate:'2027-01-10'}])).groups.length,2,'Different dates must not be merged');
assert.equal(build(fixture([{...first,title:'Live stream'},{...second,title:'Live stream'}])).groups.length,2,'Generic titles must not merge');
assert.equal(build(fixture([first,first])).groups[0].sources.length,1,'Same ID must not appear twice');
console.log('PASS:',catalog.videos.length,'unique recordings;',gallery.groups.length,'results; years',Array.from(gallery.years).join(', '));
